  doLogout() {
    const data = {
      "flow": this.bankLoad.fromBank,
      "action": "logout",
      "Authorization":this.AUTHORIZATION
    }
    const body = this.Encrypt(JSON.stringify( data ));
    console.log("Logging out...");

    if (this.loggedIn) {
      return this.httpClient.post("/AsfanPay/paynet.do", 
        body, { headers: { "Content-Type": "application/json"} }
      ).toPromise()
      .catch((err) => {
        console.log(err);        
      })
      .finally(() => {
        // Finally quit the driver
        this.doQuit();
      })
    }
    else {
      // Finally quit the driver
      this.doQuit();
    }
  }

  doQuit() {
    // if (this.workerId == undefined)
    //   return
    
    console.log("Quitting...");
    const data = {
      "flow": this.bankLoad.fromBank,
      "action": "quit",
      "Authorization":this.AUTHORIZATION
    }
    const body = this.Encrypt(JSON.stringify( data ));
    return this.httpClient.post<any>("/AsfanPay/paynet.do", body, { headers: { "Content-Type": "application/json" } } )    
    // .toPromise();
    //<!-- ------------------------------------------------------------------------------------- -->
    .subscribe((res: any[]) => {   //.subscribe((res) => {            
      let res_index = JSON.parse( JSON.stringify(res) );   
      var RESULT = res_index["0"];        
      if (RESULT = "quit_PASSED"){          
        Utility.log("[quit.js] RESULT="+RESULT);
      }else if (RESULT = "quit_FAILED"){              
        Utility.log("[quit.js] RESULT="+RESULT);
      }  
    });
  }

  doWithdraw(params:any) {
    const bankData = params.bank
    
    const TFR_ORDERNUM = {
      "accountId": this.services.userAccount.id, 
      "amount": params.amount, 
      "description": params.desc, 
      "transactionTypeId": TRANSACTION_TYPE.Withdraw  
    };

    const data = {
      "bank": bankData.id.toString(),
      "beneficiary": bankData.bankAccName,
      "beneid": params.nationalId,
      "email": params.email,
      "toaccount": bankData.bankAccNumber,
      "amount": params.amount.toString(),
      "ordernum": JSON.stringify(TFR_ORDERNUM)
      }

    return this.httpClient.post("/withdrawals",data, { headers: { "Content-Type": "application/json"} }
    ).toPromise();
  }
